import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resumeToCvMarkdown } from '../lib/resume/to-cv-md.mjs';
import { absorb } from '../lib/resume/absorb.mjs';
import { serialize } from '../lib/resume/model.mjs';

const example = readFileSync(new URL('./fixtures/resume/cv-example-shape.md', import.meta.url), 'utf8');
const EM = '—';
const entriesTo = (md, dash) => md.replace(/^(### .+?) -- /gm, `$1 ${dash} `);
const rowsTo = (md, dash) => md.replace(/^(- \*\*.+?\*\*(?: \([^()]*\))?) -- /gm, `$1 ${dash} `);

function absorbsLossless(md) {
  const first = absorb(md, null);
  assert.deepEqual(first.report.unparsed, []);
  assert.equal(first.lossless, true);
  assert.equal(resumeToCvMarkdown(first.data), md, 'gen reproduces the file byte for byte');
  const second = absorb(md, first.data);
  assert.equal(second.lossless, true);
  assert.equal(serialize(second.data), serialize(first.data), 'a second absorb changes nothing');
  return first.data.careerOps.cvStyle;
}

test('a title in -- over em-dash entry headings absorbs lossless', () => {
  const md = entriesTo(example, EM);
  assert.notEqual(md, example);
  const style = absorbsLossless(md);
  assert.equal(style.dash, EM);
  assert.equal(style.titleDash, '--');
  assert.equal(style.rowDash, '--');
});

test('em-dash list rows under -- headings absorb lossless', () => {
  const md = rowsTo(example, EM);
  assert.notEqual(md, example);
  const style = absorbsLossless(md);
  assert.equal(style.dash, '--');
  assert.equal(style.rowDash, EM);
  assert.equal('titleDash' in style, false);
});

test('an em-dash title over -- entry headings absorbs lossless', () => {
  const style = absorbsLossless(example.replace('# CV -- ', `# CV ${EM} `));
  assert.equal(style.dash, '--');
  assert.equal(style.titleDash, EM);
});

test('a file with one dash stores no per-place dash', () => {
  for (const md of [example, rowsTo(entriesTo(example, EM), EM).replace('# CV -- ', `# CV ${EM} `)]) {
    const style = absorbsLossless(md);
    assert.equal('titleDash' in style, false);
    assert.equal('rowDash' in style, false);
  }
});

test('two entry headings that disagree are still refused', () => {
  const md = example.replace(/^(### .+?) -- /m, `$1 ${EM} `);
  assert.equal(absorb(md, null).lossless, false);
});

const EN = '–';
const cv = (...lines) => [...lines, ''].join('\n');
const job = (dash = '--') => ['## Work Experience', '', `### Acme ${dash} City`, '', '**Engineer**', '2020 -- 2024', ''];
const project = (dash) => ['## Projects', '', `- **Tool** (2021) ${dash} A CLI.`];

test('a dash inside an experience bullet does not set the list rows\' dash', () => {
  const style = absorbsLossless(cv('# CV -- Pat Example', '', ...job(), `- **Latency** ${EM} cut p99 by 40%`, '', ...project('--')));
  assert.equal(style.dash, '--');
  assert.equal('rowDash' in style, false);
});

test('a dash inside a summary or an unknown section does not set the list rows\' dash', () => {
  for (const heading of ['Professional Summary', 'Highlights']) {
    const style = absorbsLossless(cv('# CV -- Pat Example', '', `## ${heading}`, '', `- **Focus** ${EM} platform work`, '', ...job(), '- did x', '', ...project('--')));
    assert.equal('rowDash' in style, false, heading);
  }
  // -- and an en dash compare equal in the gate, so only the regenerated bytes show a rewrite.
  absorbsLossless(cv(`# CV ${EN} Pat Example`, '', '## Professional Summary', '', '- **Focus** -- platform work', '', ...job(EN), '- did x', '', ...project(EN)));
});

test('an education row and a row with a comma field keep their own dash', () => {
  const rows = [
    ['## Education', '', `- MS Computer Science, State University (2018) ${EM} Thesis on caching`],
    ['## Certifications', '', `- **CKA**, CNCF (2022) ${EM} Kubernetes admin`],
  ];
  for (const section of rows) {
    const style = absorbsLossless(cv('# CV -- Pat Example', '', ...job(), '- did x', '', ...section));
    assert.equal(style.dash, '--', section[0]);
    assert.equal(style.rowDash, EM, section[0]);
  }
});

test('an en dash in each place is kept where the others use --', () => {
  assert.equal(absorbsLossless(cv(`# CV ${EN} Pat Example`, '', ...job(), '- did x', '', ...project('--'))).titleDash, EN);
  assert.equal(absorbsLossless(cv('# CV -- Pat Example', '', ...job(EN), '- did x', '', ...project('--'))).dash, EN);
  assert.equal(absorbsLossless(cv('# CV -- Pat Example', '', ...job(), '- did x', '', ...project(EN))).rowDash, EN);
});
